"""Generate a large dbt project and an empty DuckDB warehouse for benchmarking.

    uv run python scripts/generate_bench_project.py ~/repos/dbt-ls-projects/bench
    uv run dbt-ls check ~/repos/dbt-ls-projects/bench

The warehouse holds tables with columns but no rows: dbt-ls only reads
metadata. What is generated, with the default sizes:

- models in three layers (staging, intermediate, marts), each with a matching
  table in `main`, `main_intermediate` or `main_marts`
- raw schemas, half of them documented as sources and half not
- unrelated schemas the project never mentions
- seeds: CSVs with a few rows, half loaded into `main`, half into the custom
  schema `main_lookups` that `_seeds.yml` declares; every fifth mart joins one
"""

import argparse
import csv
import random
import shutil
from pathlib import Path

import duckdb

TYPES = [
    "INTEGER",
    "BIGINT",
    "VARCHAR",
    "DECIMAL(18,2)",
    "DOUBLE",
    "BOOLEAN",
    "DATE",
    "TIMESTAMP",
]
WORDS = [
    "order", "customer", "payment", "invoice", "product", "shipment", "account",
    "session", "event", "ticket", "campaign", "store", "employee", "contract",
    "device", "region", "supplier", "refund", "visit", "booking",
]  # fmt: skip
FIELDS = [
    "amount", "status", "created_at", "updated_at", "name", "code", "quantity",
    "price", "currency", "country", "email", "type", "category", "score",
    "is_active", "started_at", "ended_at", "total", "discount", "channel",
    "reference", "comment", "rank", "weight", "source_system",
]  # fmt: skip


def columns(rng: random.Random, count: int) -> list[tuple[str, str]]:
    """`id` plus `count - 1` columns with unique names."""
    names = rng.sample(FIELDS, k=min(count - 1, len(FIELDS)))
    names += [f"attr_{i}" for i in range(count - 1 - len(names))]
    return [("id", "BIGINT")] + [(n, rng.choice(TYPES)) for n in names]


def create_table(con, schema: str, table: str, cols: list[tuple[str, str]]) -> None:
    body = ", ".join(f'"{name}" {type_}' for name, type_ in cols)
    con.execute(f'CREATE TABLE "{schema}"."{table}" ({body})')


def select_list(alias: str, cols: list[tuple[str, str]], indent: str) -> str:
    return (",\n" + indent).join(f"{alias}.{name}" for name, _ in cols)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("path", type=Path, help="Directory to create (replaced if it exists)")
    p.add_argument("--models", type=int, default=2000)
    p.add_argument("--source-schemas", type=int, default=20)
    p.add_argument("--unrelated-schemas", type=int, default=20)
    p.add_argument("--tables-per-schema", type=int, default=100)
    p.add_argument("--columns", type=int, default=25, help="Average columns per table")
    p.add_argument("--seeds", type=int, default=20)
    p.add_argument("--seed", type=int, default=1)
    args = p.parse_args()

    rng = random.Random(args.seed)
    root: Path = args.path.expanduser()
    if root.exists():
        if not (root / ".dbt-ls-bench").exists():
            p.error(f"{root} exists and was not made by this script")
        shutil.rmtree(root)
    (root / "models").mkdir(parents=True)
    (root / ".dbt-ls-bench").write_text("generated by scripts/generate_bench_project.py\n")

    def width() -> int:
        return max(3, int(rng.gauss(args.columns, args.columns / 4)))

    (root / "dbt_project.yml").write_text(
        "name: 'bench'\nversion: '1.0.0'\nprofile: 'bench'\n"
        'model-paths: ["models"]\n'
        'seed-paths: ["seeds"]\n'
        "models:\n  bench:\n"
        "    intermediate:\n      +schema: intermediate\n"
        "    marts:\n      +schema: marts\n"
    )
    (root / "profiles.yml").write_text(
        "bench:\n  target: dev\n  outputs:\n    dev:\n"
        "      type: duckdb\n      path: bench.duckdb\n      schema: main\n      threads: 4\n"
    )

    con = duckdb.connect(str(root / "bench.duckdb"))
    con.execute("BEGIN")
    tables = 0
    total_columns = 0

    # Raw schemas: the first half is documented in sources.yml, the rest is not.
    raw: list[tuple[str, str, list]] = []
    documented = []
    for s in range(args.source_schemas):
        schema = f"raw_{WORDS[s % len(WORDS)]}_{s:02d}"
        con.execute(f'CREATE SCHEMA "{schema}"')
        is_documented = s < args.source_schemas / 2
        entries = []
        for t in range(args.tables_per_schema):
            table = f"{WORDS[t % len(WORDS)]}s_{t:03d}"
            cols = columns(rng, width())
            create_table(con, schema, table, cols)
            tables += 1
            total_columns += len(cols)
            if is_documented:
                raw.append((schema, table, cols))
                entries.append(table)
        if is_documented:
            documented.append((schema, entries))

    # Schemas the project never mentions.
    for s in range(args.unrelated_schemas):
        schema = f"other_{WORDS[s % len(WORDS)]}_{s:02d}"
        con.execute(f'CREATE SCHEMA "{schema}"')
        for t in range(args.tables_per_schema):
            cols = columns(rng, width())
            create_table(con, schema, f"{WORDS[t % len(WORDS)]}_data_{t:03d}", cols)
            tables += 1
            total_columns += len(cols)

    sources = ["version: 2", "", "sources:"]
    for schema, entries in documented:
        sources += [f"  - name: {schema}", "    tables:"]
        sources += [f"      - name: {table}" for table in entries]
    (root / "models" / "sources.yml").write_text("\n".join(sources) + "\n")

    # Seeds: small lookup tables. The header is what dbt-ls reads; the rows
    # are only there to make them look like seeds.
    con.execute('CREATE SCHEMA "main_lookups"')
    seeds: list[tuple[str, list]] = []
    seeds_yml = ["version: 2", "", "seeds:"]
    for i in range(args.seeds):
        in_lookups = i % 2 == 0
        folder = "lookups" if in_lookups else "reference"
        name = f"{WORDS[i % len(WORDS)]}_{'codes' if in_lookups else 'mapping'}_{i:02d}"
        cols = [("id", "BIGINT"), ("code", "VARCHAR"), ("label", "VARCHAR")]
        spare = [f for f in FIELDS if f not in ("code", "label")]
        cols += [(f, "VARCHAR") for f in rng.sample(spare, k=rng.randint(0, 4))]
        path = root / "seeds" / folder / f"{name}.csv"
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", newline="") as f:
            writer = csv.writer(f)
            writer.writerow([c for c, _ in cols])
            for row in range(1, 6):
                writer.writerow(
                    [row, f"C{row:02d}", f"{WORDS[row]} {row}"]
                    + [f"{c}_{row}" for c, _ in cols[3:]]
                )
        create_table(con, "main_lookups" if in_lookups else "main", name, cols)
        tables += 1
        total_columns += len(cols)
        seeds.append((name, cols))
        if in_lookups:
            seeds_yml += [
                f"  - name: {name}",
                "    config:",
                "      schema: lookups",
            ]
    (root / "seeds" / "_seeds.yml").write_text("\n".join(seeds_yml) + "\n")

    # Models: half staging, 30 % intermediate, 20 % marts.
    n_staging = args.models // 2
    n_intermediate = args.models * 3 // 10
    n_marts = args.models - n_staging - n_intermediate
    con.execute('CREATE SCHEMA "main_intermediate"')
    con.execute('CREATE SCHEMA "main_marts"')
    layers = {
        "staging": ("main", []),
        "intermediate": ("main_intermediate", []),
        "marts": ("main_marts", []),
    }
    schema_yml: dict[str, list[str]] = {layer: ["version: 2", "", "models:"] for layer in layers}

    def write_model(layer: str, name: str, sql: str, cols: list[tuple[str, str]]) -> None:
        folder = root / "models" / layer / name.split("__")[0]
        folder.mkdir(parents=True, exist_ok=True)
        (folder / f"{name}.sql").write_text(sql)
        schema, models = layers[layer]
        create_table(con, schema, name, cols)
        models.append((name, cols))
        # Every second model is documented, without types, as in a real project.
        if len(models) % 2 == 0:
            schema_yml[layer] += [f"  - name: {name}", "    columns:"]
            schema_yml[layer] += [f"      - name: {c}" for c, _ in cols]

    for i in range(n_staging):
        schema, table, cols = raw[i % len(raw)]
        name = f"stg_{schema}__{table}_{i:04d}"
        header = "{{ config(materialized='view') }}\n\n" if i % 3 == 0 else ""
        sql = (
            f"{header}with source as (\n"
            f"    select * from {{{{ source('{schema}', '{table}') }}}}\n"
            "),\n"
            "renamed as (\n"
            "    select\n        " + select_list("s", cols, "        ") + "\n"
            "    from source s\n"
            ")\n"
            "select * from renamed\n"
        )
        write_model("staging", name, sql, cols)

    def joined(
        layer: str, prefix: str, index: int, parents: list, lookup=None
    ) -> None:
        (left, left_cols), (right, right_cols) = rng.sample(parents, k=2)
        keep_left = left_cols[: max(2, len(left_cols) // 2)]
        taken = {c for c, _ in keep_left}
        keep_right = [c for c in right_cols[1:] if c[0] not in taken][:8]
        name = f"{prefix}_{WORDS[index % len(WORDS)]}__{index:04d}"
        # A seed to label the rows with, the way marts use lookup tables.
        seed_cte = seed_select = seed_join = ""
        extra = []
        if lookup is not None:
            seed_cte = f",\nl as (\n    select * from {{{{ ref('{lookup}') }}}}\n)"
            seed_select = ",\n    l.label as lookup_label"
            seed_join = "left join l on l.id = a.id\n"
            extra = [("lookup_label", "VARCHAR")]
        sql = (
            "with a as (\n"
            f"    select * from {{{{ ref('{left}') }}}}\n"
            "),\n"
            "b as (\n"
            f"    select * from {{{{ ref('{right}') }}}}\n"
            f"){seed_cte}\n"
            "select\n    " + select_list("a", keep_left, "    ")
            + ("".join(f",\n    b.{c}" for c, _ in keep_right))
            + seed_select
            + "\nfrom a\nleft join b on b.id = a.id\n"
            + seed_join
        )
        write_model(layer, name, sql, keep_left + keep_right + extra)

    for i in range(n_intermediate):
        joined("intermediate", "int", i, layers["staging"][1])
    for i in range(n_marts):
        lookup = seeds[i // 5 % len(seeds)][0] if seeds and i % 5 == 0 else None
        joined("marts", "fct" if i % 2 else "dim", i, layers["intermediate"][1], lookup)

    for layer, lines in schema_yml.items():
        (root / "models" / layer / f"_{layer}.yml").write_text("\n".join(lines) + "\n")
    for _, models in layers.values():
        tables += len(models)
        total_columns += sum(len(cols) for _, cols in models)

    con.execute("COMMIT")
    con.execute("CHECKPOINT")
    con.close()

    print(f"project   {root}")
    print(f"models    {args.models} ({n_staging} staging, {n_intermediate} intermediate, {n_marts} marts)")
    print(f"sources   {len(raw)} documented tables in {len(documented)} schemas")
    print(f"seeds     {len(seeds)}, half of them in main_lookups")
    print(
        f"warehouse {tables} tables, {total_columns} columns, "
        f"{args.source_schemas + args.unrelated_schemas + 4} schemas, no rows"
    )


if __name__ == "__main__":
    main()
